const KEYWORD_INDEX = GUIDELINES.map((g) => ({
  id: g.id,
  keywords: g.keywords,
}));

function countHits(text, keywords) {
  const lower = text.toLowerCase();
  let score = 0;
  for (const kw of keywords) {
    if (lower.includes(kw.toLowerCase())) {
      score += kw.length >= 3 ? 2 : 1;
    }
  }
  return score;
}

export function retrieveGuidelines(text, topK = 3) {
  const q = String(text || "");
  const scored = GUIDELINES.map((g, i) => ({
    ...g,
    score: countHits(q, KEYWORD_INDEX[i].keywords),
  }))
    .filter((g) => g.score > 0)
    .sort((a, b) => b.score - a.score);

  return scored.slice(0, topK);
}
